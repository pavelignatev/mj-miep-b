"""Игра «Угадай эпоху/понятие» — МЖ-МИЭП, вариант Б."""

import random

cards = {
    "эпоха разума и критики предрассудков": "просвещение",
    "личность, чувство и свобода в центре эстетики": "романтизм",
    "Гора, Путь и Восходитель": "орософия",
    "участник мировой политики, способный влиять на события": "актор",
    "приоритеты государства во внешней политике": "национальный интерес",
    "взаимодействие через международные организации": "многосторонность",
}

print("=" * 45)
print("  УГАДАЙ ПОНЯТИЕ")
print("  МЖ-МИЭП · вариант Б")
print("=" * 45)

score = 0
for i, (hint, term) in enumerate(random.sample(list(cards.items()), k=5), start=1):
    answer = input(f"{i}/5. {hint}\nОтвет: ").strip().lower()
    if answer == term:
        print("Есть!\n")
        score += 1
    else:
        print(f"Правильно: «{term}».\n")

print("=" * 45)
print(f"Счёт: {score}/5")
